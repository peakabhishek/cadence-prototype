def _lin(v):
    v = v / 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

def lum(h):
    h = h.lstrip("#"); r, g, b = (int(h[i:i+2], 16) for i in (0, 2, 4))
    return 0.2126*_lin(r) + 0.7152*_lin(g) + 0.0722*_lin(b)

def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

def check(key):
    c = OPTIONS[key]["c"]; out = []
    for f, b, use, mn in PAIRS:
        if f not in c or b not in c: continue
        r = ratio(c[f], c[b])
        out.append((f, b, c[f], c[b], use, mn, r, (r >= mn) if mn else None))
    return out

